/** Le nom à afficher pour le langage écrit après les guillemets d'un bloc de code. */
export function nomDuLangage(langage: string): string {
  const ecrit = langage.trim();
  if (ecrit === '') return 'Code';
  return NOMS.get(ecrit.toLowerCase()) ?? ecrit;
}
